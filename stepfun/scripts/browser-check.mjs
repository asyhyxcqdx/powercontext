import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { browser, pageFor } from './browser-common.mjs';
const gpu = process.argv.includes('--gpu');
const instance = await browser(gpu);
const backend = gpu ? 'webgpu' : 'wasm';
const evidence = { at: new Date().toISOString(), browser: instance.version(), checks: [] };
try {
  const page = await pageFor(instance);
  const events = []; page.on('request', request => events.push({ method: request.method(), url: request.url() }));
  const suffix = Date.now();
  await page.locator('#library').fill(`smoke_${suffix}`);
  await page.locator('#open').click();
  await page.waitForFunction(() => !document.querySelector('#sample').disabled || document.querySelector('#status').classList.contains('error'));
  assert.equal(await page.locator('#status').getAttribute('class'), '', await page.locator('#status').textContent());
  assert.ok((await page.locator('#backend').textContent()).includes(backend.toUpperCase()));
  if (!gpu) assert.match(await page.locator('#status').textContent(), /WASM/);
  evidence.checks.push(gpu ? 'auto mode selects real WebGPU and displays backend' : 'WebGPU-disabled browser automatically selects WASM and displays fallback');
  await page.locator('#sample').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已导入 32'));
  await page.locator('#query').fill('How can I restore records after accidentally deleting a database table?');
  await page.locator('#search').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('找到'));
  assert.equal(await page.locator('.result').count(), 5);
  assert.match(await page.locator('#results').textContent(), /Recovering deleted database records/);
  evidence.checks.push('browser embedding -> real seekdb import -> hybrid search retrieves relevant original text');
  await page.screenshot({ path: `artifacts/${backend}-ui.png`, fullPage: true });
  await page.locator('#files').setInputFiles({ name: 'telescope.txt', mimeType: 'text/plain', buffer: Buffer.from('Veloran observatory records a unique teal telescope called Astrolume. Its lens captures violet starlight.') });
  await page.locator('#import').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('已导入 1'));
  evidence.checks.push('actual file picker imports a text document');
  const checks = await page.evaluate(async (suffix) => {
    const lib = window.edgeLibrary;
    const corpus = await (await fetch('/data/evaluation.json')).json();
    const duplicate = await lib.import(corpus.documents, 8);
    if (duplicate.count !== 33) throw new Error('Repeated import created duplicates');
    await lib.import([{ id: 'unique-new', title: 'New nebula record', text: 'Nebulax cobalt observatory has a violet telescope named Tesseract. This is the newly imported observatory record.' }], 1);
    const inserted = await lib.search('Nebulax cobalt Tesseract observatory');
    if (!inserted.results.some(r => r.id === 'unique-new')) throw new Error('Incremental import is not searchable after refresh');
    await lib.open(`empty_${suffix}`, 'q8', 'auto');
    const empty = await lib.search('Nebulax cobalt Tesseract observatory');
    if (empty.results.length) throw new Error('Different collection leaked old results');
    await lib.open(`smoke_${suffix}`, 'q8', 'auto');
    const restored = await lib.search('Nebulax cobalt Tesseract observatory');
    if (!restored.results.some(r => r.id === 'unique-new')) throw new Error('Switch-back lost original collection');
    const invalid = await fetch('/api/import', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ library: `smoke_${suffix}`, dtype: 'q8', documents: [{ id: 'bad', title: 'bad', text: 'bad', embedding: [1,2] }] }) });
    if (invalid.status !== 400) throw new Error('Invalid vectors were accepted');
    return ['repeat import is idempotent', 'new document visible after index refresh', 'switching collections is isolated', 'switching back preserves documents', 'invalid vectors rejected'];
  }, suffix);
  evidence.checks.push(...checks);
  await page.reload(); await page.waitForFunction(() => !!window.edgeLibrary);
  const persisted = await page.evaluate(async suffix => {
    const opened = await window.edgeLibrary.open(`smoke_${suffix}`, 'q8', 'auto');
    return { count: opened.collection.count, result: await window.edgeLibrary.search('Nebulax cobalt Tesseract observatory') };
  }, suffix);
  assert.equal(persisted.count, 34);
  assert.ok(persisted.result.results.some(r => r.id === 'unique-new'));
  evidence.checks.push('browser reload recovers persisted data');
  assert.ok(events.every(event => new URL(event.url).hostname === '127.0.0.1'));
  evidence.checks.push('all browser requests stay on local app origin; no cloud inference request');
  evidence.requests = events;
  await mkdir('artifacts', { recursive: true });
  await writeFile(`artifacts/browser-check-${backend}.json`, JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify(evidence.checks, null, 2));
} finally { await instance.close(); }
